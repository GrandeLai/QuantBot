@dataclass(frozen=True, slots=True)
class NormalH2HistoricalAudit:
    """Core-verified, non-selectable H2 return history."""

    observation_dates: tuple[date, ...]
    daily_returns: tuple[float, ...]
    execution_proof: Mapping[str, object]
    content_hash: str
    issuer: str
    _seal: object = field(default=None, repr=False, compare=False)

    def __post_init__(self) -> None:
        if self._seal is not _NORMAL_H2_AUDIT_SEAL:
            raise PermissionError(
                "normal H2 audit must be created by signature verification"
            )
        dates = tuple(self.observation_dates)
        returns = _returns(self.daily_returns)
        if len(dates) < 4 or dates != tuple(sorted(set(dates))):
            raise ValueError(
                "normal H2 audit dates must contain at least four unique ascending dates"
            )
        if len(returns) != len(dates):
            raise ValueError("normal H2 audit returns must be date-aligned")
        _digest(self.content_hash, "normal H2 audit content_hash")
        if not isinstance(self.issuer, str) or not self.issuer.strip():
            raise ValueError("normal H2 audit issuer is required")
        object.__setattr__(self, "observation_dates", dates)
        object.__setattr__(self, "daily_returns", returns)
        object.__setattr__(
            self,
            "execution_proof",
            MappingProxyType(dict(self.execution_proof)),
        )

    @property
    def sharpe_annual(self) -> float:
        return _annualized_sharpe(self.daily_returns)

    def require_compatible(
        self,
        *,
        mode: str,
        request_start: date,
        request_end: date,
        warmup_start: date,
        warmup_end: date,
        dataset_hash: str,
        cost_model_hash: str,
        code_hash: str,
    ) -> None:
        """Fail before claim when H2 cannot be compared with the requested H1."""

        expected = {
            "permit_mode": mode,
            "permit_request_start": request_start.isoformat(),
            "permit_request_end": request_end.isoformat(),
            "permit_warmup_start": warmup_start.isoformat(),
            "permit_warmup_end": warmup_end.isoformat(),
            "permit_dataset_hash": dataset_hash,
            "permit_cost_model_hash": cost_model_hash,
            "permit_code_hash": code_hash,
        }
        mismatches = [
            name
            for name, value in expected.items()
            if self.execution_proof.get(name) != value
        ]
        if mismatches:
            raise PermissionError(
                "normal H2 audit is not comparable with current H1: "
                + ",".join(mismatches)
            )

    def require_materialization(
        self,
        *,
        input_materialization_hash: str,
        session_hash: str,
    ) -> None:
        mismatches = []
        if self.execution_proof.get("input_materialization_hash") != input_materialization_hash:
            mismatches.append("input_materialization_hash")
        if self.execution_proof.get("session_hash") != session_hash:
            mismatches.append("session_hash")
        if mismatches:
            raise PermissionError(
                "normal H2 audit does not share the current H1 materialization: "
                + ",".join(mismatches)
            )


@dataclass(frozen=True, slots=True)
class NormalAdaptiveValidationArtifact:
    """Signed adaptive H1/H2 statistics frozen before sealed evaluation."""

    observation_dates: tuple[date, ...]
    h1_daily_returns: tuple[float, ...]
    h2_daily_returns: tuple[float, ...]
    dsr: DeflatedSharpeResult
    pbo_result: ProbabilityOfBacktestOverfittingResult
    content_hash: str
    issuer: str
    strategy_protocol_hash: str
    cost_model_hash: str
    stockbot_source_hash: str
    adapter_artifact_hash: str
    _seal: object = field(default=None, repr=False, compare=False)

    def __post_init__(self) -> None:
        if self._seal is not _NORMAL_ADAPTIVE_VALIDATION_SEAL:
            raise PermissionError(
                "normal adaptive validation must be created by signature verification"
            )
        dates = tuple(self.observation_dates)
        h1 = _returns(self.h1_daily_returns)
        h2 = _returns(self.h2_daily_returns)
        if (
            len(dates) < 4
            or dates != tuple(sorted(set(dates)))
            or len(h1) != len(dates)
            or len(h2) != len(dates)
        ):
            raise ValueError("normal adaptive H1/H2 histories must be date-aligned")
        if not isinstance(self.dsr, DeflatedSharpeResult):
            raise TypeError("normal adaptive dsr must be DeflatedSharpeResult")
        if not isinstance(self.pbo_result, ProbabilityOfBacktestOverfittingResult):
            raise TypeError(
                "normal adaptive pbo_result must be ProbabilityOfBacktestOverfittingResult"
            )
        for name in (
            "content_hash",
            "strategy_protocol_hash",
            "cost_model_hash",
            "stockbot_source_hash",
            "adapter_artifact_hash",
        ):
            _digest(getattr(self, name), name)
        if not isinstance(self.issuer, str) or not self.issuer.strip():
            raise ValueError("normal adaptive validation issuer is required")
        object.__setattr__(self, "observation_dates", dates)
        object.__setattr__(self, "h1_daily_returns", h1)
        object.__setattr__(self, "h2_daily_returns", h2)

    @property
    def pbo(self) -> float:
        return self.pbo_result.probability

    def require_compatible(
        self,
        *,
        strategy_protocol_hash: str,
        cost_model_hash: str,
        stockbot_source_hash: str,
        adapter_artifact_hash: str,
    ) -> None:
        expected = {
            "strategy_protocol_hash": strategy_protocol_hash,
            "cost_model_hash": cost_model_hash,
            "stockbot_source_hash": stockbot_source_hash,
            "adapter_artifact_hash": adapter_artifact_hash,
        }
        mismatches = [
            name for name, value in expected.items() if getattr(self, name) != value
        ]
        if mismatches:
            raise PermissionError(
                "normal adaptive validation is not compatible with sealed H1: "
                + ",".join(mismatches)
            )


def normal_trial_return_history_hash(
    observation_dates: Sequence[str | date],
    daily_returns: Sequence[object],
) -> str:
    dates = tuple(_date(value, "normal trial observation date") for value in observation_dates)
    if dates != tuple(sorted(set(dates))):
        raise ValueError("normal trial observation dates must be unique and sorted")
    returns = _returns(daily_returns)
    if len(returns) != len(dates):
        raise ValueError("normal trial returns must align with observation dates")
    return hash_payload(
        {
            "observation_dates": [value.isoformat() for value in dates],
            "daily_returns": list(returns),
        }
    )


def trusted_normal_trial_keys(environ: Mapping[str, str]) -> dict[str, bytes]:
    raw = str(environ.get(NORMAL_TRIAL_KEYS_ENV, "") or "").strip()
    if not raw:
        raise ValueError(f"{NORMAL_TRIAL_KEYS_ENV} must configure trusted issuer keys")
    try:
        payload = json.loads(raw)
        keys = {str(issuer): bytes.fromhex(value) for issuer, value in payload.items()}
    except (AttributeError, TypeError, ValueError, json.JSONDecodeError) as error:
        raise ValueError(
            f"{NORMAL_TRIAL_KEYS_ENV} must be a JSON object of hex keys"
        ) from error
    if not keys or any(not issuer.strip() or len(key) < 16 for issuer, key in keys.items()):
        raise ValueError(f"{NORMAL_TRIAL_KEYS_ENV} keys must contain at least 16 bytes")
    return keys


def load_normal_h2_historical_audit(
    path: Path | str,
    *,
    trusted_keys: Mapping[str, bytes],
) -> NormalH2HistoricalAudit:
    try:
        payload = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ValueError("normal H2 audit artifact cannot be read") from error
    return verify_normal_h2_historical_audit(payload, trusted_keys=trusted_keys)


def verify_normal_h2_historical_audit(
    payload: object,
    *,
    trusted_keys: Mapping[str, bytes],
) -> NormalH2HistoricalAudit:
    if not isinstance(payload, dict) or set(payload) != _ARTIFACT_FIELDS:
        raise ValueError("normal H2 audit artifact fields are invalid")
    artifact = dict(payload)
    signature = _digest(artifact.pop("signature"), "normal H2 artifact signature")
    content_hash = _digest(
        artifact.pop("content_hash"), "normal H2 artifact content_hash"
    )
    if artifact.get("artifact_version") != NORMAL_H2_AUDIT_ARTIFACT_VERSION:
        raise ValueError("normal H2 audit artifact_version is unsupported")
    if artifact.get("strategy_family") != "normal":
        raise ValueError("normal H2 audit strategy_family must be normal")
    if artifact.get("policy_version") != ACCEPTANCE_POLICY_VERSION:
        raise ValueError("normal H2 audit policy_version is not current")
    if artifact.get("experiment_id") != NORMAL_H2_EXPERIMENT_ID:
        raise ValueError("normal H2 audit experiment_id is invalid")
    if artifact.get("disposition") != "completed_rejected":
        raise ValueError("normal H2 audit must remain completed_rejected")
    issuer = _issuer(artifact.get("issuer"), "normal H2 audit artifact")
    _verify_signature(
        content_hash=content_hash,
        signature=signature,
        unsigned=artifact,
        issuer=issuer,
        trusted_keys=trusted_keys,
        name="normal H2 audit artifact",
    )
    raw_dates = artifact.get("observation_dates")
    if not isinstance(raw_dates, list):
        raise ValueError("normal H2 audit observation_dates must be an array")
    dates = tuple(_date(value, "normal H2 audit observation date") for value in raw_dates)
    returns = _returns(artifact.get("daily_returns"))
    if len(dates) < 4 or dates != tuple(sorted(set(dates))) or len(returns) != len(dates):
        raise ValueError("normal H2 audit returns must have aligned ascending dates")
    proof = _verify_execution_proof(
        artifact.get("execution_evidence"),
        observation_dates=dates,
        daily_returns=returns,
        trusted_keys=trusted_keys,
    )
    return NormalH2HistoricalAudit(
        observation_dates=dates,
        daily_returns=returns,
        execution_proof=proof,
        content_hash=content_hash,
        issuer=issuer,
        _seal=_NORMAL_H2_AUDIT_SEAL,
    )


