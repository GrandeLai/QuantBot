def verify_normal_adaptive_validation_artifact(
    payload: object,
    *,
    trusted_keys: Mapping[str, bytes],
) -> NormalAdaptiveValidationArtifact:
    """Verify and independently recompute frozen adaptive DSR/PBO."""

    if not isinstance(payload, dict) or set(payload) != _ADAPTIVE_ARTIFACT_FIELDS:
        raise ValueError("normal adaptive validation artifact fields are invalid")
    artifact = dict(payload)
    signature = _digest(
        artifact.pop("signature"), "normal adaptive artifact signature"
    )
    content_hash = _digest(
        artifact.pop("content_hash"), "normal adaptive artifact content_hash"
    )
    if (
        artifact.get("artifact_version")
        != NORMAL_ADAPTIVE_VALIDATION_ARTIFACT_VERSION
    ):
        raise ValueError("normal adaptive validation artifact_version is unsupported")
    if artifact.get("strategy_family") != "normal":
        raise ValueError("normal adaptive validation strategy_family must be normal")
    if artifact.get("policy_version") != ACCEPTANCE_POLICY_VERSION:
        raise ValueError("normal adaptive validation policy_version is not current")
    if artifact.get("experiment_id") != NORMAL_H1_EXPERIMENT_ID:
        raise ValueError("normal adaptive validation experiment_id is invalid")
    if artifact.get("source_mode") != "adaptive_development":
        raise ValueError("normal adaptive validation source_mode is invalid")
    if artifact.get("candidate_survived") is not True:
        raise ValueError("normal adaptive validation candidate did not survive")
    if artifact.get("declared_trials") != 2 or artifact.get("completed_trials") != 2:
        raise ValueError("normal adaptive validation requires exactly two completed trials")
    window = require_exact_normal_experiment_window(
        mode="adaptive_development",
        request_start=_date(artifact.get("request_start"), "request_start"),
        request_end=_date(artifact.get("request_end"), "request_end"),
        warmup_start=_date(artifact.get("warmup_start"), "warmup_start"),
        warmup_end=_date(artifact.get("warmup_end"), "warmup_end"),
    )
    issuer = _issuer(artifact.get("issuer"), "normal adaptive validation artifact")
    _verify_signature(
        content_hash=content_hash,
        signature=signature,
        unsigned=artifact,
        issuer=issuer,
        trusted_keys=trusted_keys,
        name="normal adaptive validation artifact",
    )
    for name in (
        "dataset_hash",
        "input_materialization_hash",
        "strategy_protocol_hash",
        "h1_config_hash",
        "h2_config_hash",
        "cost_model_hash",
        "stockbot_source_hash",
        "adapter_artifact_hash",
        "h1_code_hash",
        "h2_code_hash",
        "h1_report_hash",
        "h2_report_hash",
        "h2_audit_artifact_hash",
        "h1_return_history_hash",
        "h2_return_history_hash",
    ):
        _digest(artifact.get(name), name)
    if artifact["h1_config_hash"] == artifact["h2_config_hash"]:
        raise ValueError("normal adaptive H1/H2 config hashes must be distinct")
    if artifact["h1_code_hash"] != artifact["h2_code_hash"]:
        raise ValueError("normal adaptive H1/H2 code hashes must match")
    if artifact["h1_report_hash"] == artifact["h2_report_hash"]:
        raise ValueError("normal adaptive H1/H2 report hashes must be distinct")

    raw_dates = artifact.get("observation_dates")
    if not isinstance(raw_dates, list):
        raise ValueError("normal adaptive observation_dates must be an array")
    dates = tuple(_date(value, "normal adaptive observation date") for value in raw_dates)
    h1_returns = _returns(artifact.get("h1_daily_returns"))
    h2_returns = _returns(artifact.get("h2_daily_returns"))
    if (
        len(dates) < 4
        or dates != tuple(sorted(set(dates)))
        or len(h1_returns) != len(dates)
        or len(h2_returns) != len(dates)
        or min(dates) < window.request_start
        or max(dates) > window.request_end
    ):
        raise ValueError("normal adaptive H1/H2 returns must be date-aligned")
    if artifact["h1_return_history_hash"] != normal_trial_return_history_hash(
        dates, h1_returns
    ):
        raise ValueError("normal adaptive H1 return_history_hash mismatch")
    if artifact["h2_return_history_hash"] != normal_trial_return_history_hash(
        dates, h2_returns
    ):
        raise ValueError("normal adaptive H2 return_history_hash mismatch")

    dsr = deflated_sharpe_ratio(
        h1_returns,
        (_annualized_sharpe(h1_returns), _annualized_sharpe(h2_returns)),
    )
    partition = cscv_partition(
        {
            NORMAL_H1_EXPERIMENT_ID: h1_returns,
            NORMAL_H2_EXPERIMENT_ID: h2_returns,
        }
    )
    if partition is None:
        raise ValueError("normal adaptive PBO is unavailable")
    pbo_result = cscv_probability_of_backtest_overfitting(
        partition.trial_returns,
        folds=partition.folds,
    )
    supplied_dsr = _probability(artifact.get("dsr_confidence"), "dsr_confidence")
    supplied_pbo = _probability(artifact.get("pbo"), "pbo")
    if abs(supplied_dsr - dsr.confidence) > 1e-12:
        raise ValueError("normal adaptive dsr_confidence does not match returns")
    if abs(supplied_pbo - pbo_result.probability) > 1e-12:
        raise ValueError("normal adaptive pbo does not match returns")
    if dsr.confidence < 0.95 or pbo_result.probability > 0.05:
        raise ValueError("normal adaptive candidate_survived conflicts with DSR/PBO")
    return NormalAdaptiveValidationArtifact(
        observation_dates=dates,
        h1_daily_returns=h1_returns,
        h2_daily_returns=h2_returns,
        dsr=dsr,
        pbo_result=pbo_result,
        content_hash=content_hash,
        issuer=issuer,
        strategy_protocol_hash=str(artifact["strategy_protocol_hash"]),
        cost_model_hash=str(artifact["cost_model_hash"]),
        stockbot_source_hash=str(artifact["stockbot_source_hash"]),
        adapter_artifact_hash=str(artifact["adapter_artifact_hash"]),
        _seal=_NORMAL_ADAPTIVE_VALIDATION_SEAL,
    )


def _verify_execution_proof(
    payload: object,
    *,
    observation_dates: tuple[date, ...],
    daily_returns: tuple[float, ...],
    trusted_keys: Mapping[str, bytes],
) -> dict[str, object]:
    if not isinstance(payload, dict) or set(payload) != _PROOF_FIELDS:
        raise ValueError("normal H2 audit proof fields are invalid")
    proof = dict(payload)
    signature = _digest(proof.pop("signature"), "normal H2 proof signature")
    content_hash = _digest(proof.pop("content_hash"), "normal H2 proof content_hash")
    if proof.get("proof_version") != NORMAL_H2_AUDIT_PROOF_VERSION:
        raise ValueError("normal H2 audit proof_version is unsupported")
    if proof.get("experiment_id") != NORMAL_H2_EXPERIMENT_ID:
        raise ValueError("normal H2 proof experiment_id is invalid")
    if proof.get("disposition") != "completed_rejected":
        raise ValueError("normal H2 proof disposition is invalid")
    if proof.get("run_type") != "historical_audit_replay":
        raise ValueError("normal H2 proof run_type must be historical_audit_replay")
    if proof.get("policy_version") != ACCEPTANCE_POLICY_VERSION:
        raise ValueError("normal H2 proof policy_version is not current")
    if not isinstance(proof.get("run_id"), str) or not str(proof["run_id"]).strip():
        raise ValueError("normal H2 proof run_id is required")
    mode = proof.get("permit_mode")
    if mode not in {"research", "adaptive_development"}:
        raise ValueError("normal H2 audit may use only development windows")
    request_start = _date(proof.get("permit_request_start"), "permit_request_start")
    request_end = _date(proof.get("permit_request_end"), "permit_request_end")
    warmup_start = _date(proof.get("permit_warmup_start"), "permit_warmup_start")
    warmup_end = _date(proof.get("permit_warmup_end"), "permit_warmup_end")
    require_exact_normal_experiment_window(
        mode=str(mode),
        request_start=request_start,
        request_end=request_end,
        warmup_start=warmup_start,
        warmup_end=warmup_end,
    )
    manifest = ValidationWindowManifest(
        strategy_family="normal",
        mode=str(mode),
        request_start=request_start,
        request_end=request_end,
        warmup_start=warmup_start,
        warmup_end=warmup_end,
        dataset_hash=_digest(proof.get("permit_dataset_hash"), "permit_dataset_hash"),
        config_hash=_digest(proof.get("permit_config_hash"), "permit_config_hash"),
        cost_model_hash=_digest(
            proof.get("permit_cost_model_hash"), "permit_cost_model_hash"
        ),
        code_hash=_digest(proof.get("permit_code_hash"), "permit_code_hash"),
    )
    if proof.get("permit_manifest_hash") != manifest.manifest_hash:
        raise ValueError("normal H2 permit_manifest_hash mismatch")
    if proof.get("permit_actual_start") != manifest.actual_start.isoformat():
        raise ValueError("normal H2 permit_actual_start mismatch")
    if proof.get("permit_actual_end") != manifest.actual_end.isoformat():
        raise ValueError("normal H2 permit_actual_end mismatch")
    if min(observation_dates) < request_start or max(observation_dates) > request_end:
        raise ValueError("normal H2 return dates are outside the permit request")
    claimed_at = _aware_datetime(proof.get("permit_claimed_at"), "permit_claimed_at")
    observed_at = _aware_datetime(
        proof.get("execution_observed_at"), "execution_observed_at"
    )
    if observed_at < claimed_at:
        raise ValueError("normal H2 execution predates its permit claim")
    for name in (
        "permit_record_hash",
        "execution_evidence_hash",
        "input_materialization_hash",
        "session_hash",
    ):
        _digest(proof.get(name), name)
    if proof.get("return_history_hash") != normal_trial_return_history_hash(
        observation_dates,
        daily_returns,
    ):
        raise ValueError("normal H2 return_history_hash mismatch")
    issuer = _issuer(proof.get("issuer"), "normal H2 audit proof")
    _verify_signature(
        content_hash=content_hash,
        signature=signature,
        unsigned=proof,
        issuer=issuer,
        trusted_keys=trusted_keys,
        name="normal H2 audit proof",
    )
    return {**proof, "content_hash": content_hash, "signature": signature}


def _verify_signature(
    *,
    content_hash: str,
    signature: str,
    unsigned: Mapping[str, object],
    issuer: str,
    trusted_keys: Mapping[str, bytes],
    name: str,
) -> None:
    if content_hash != hash_payload(dict(unsigned)):
        raise ValueError(f"{name} content_hash mismatch")
    key = trusted_keys.get(issuer)
    if key is None:
        raise ValueError(f"{name} trusted issuer key is missing")
    if not isinstance(key, bytes) or len(key) < 16:
        raise ValueError(f"{name} trusted issuer key must contain at least 16 bytes")
    expected = hmac.new(key, content_hash.encode("ascii"), sha256).hexdigest()
    if not hmac.compare_digest(expected, signature):
        raise ValueError(f"{name} signature is invalid")


def _returns(values: object) -> tuple[float, ...]:
    if isinstance(values, (str, bytes)):
        raise ValueError("normal H2 returns must be a numeric sequence")
    try:
        normalized = tuple(float(value) for value in values)  # type: ignore[arg-type]
    except (OverflowError, TypeError, ValueError) as error:
        raise ValueError("normal H2 returns must be numeric") from error
    if not normalized or any(not isfinite(value) or value <= -1.0 for value in normalized):
        raise ValueError("normal H2 returns must be finite and greater than -1")
    return normalized


def _annualized_sharpe(values: Sequence[float]) -> float:
    returns = _returns(values)
    if len(returns) < 3:
        raise ValueError("normal trial Sharpe requires at least three returns")
    mean = fsum(returns) / len(returns)
    variance = fsum((value - mean) ** 2 for value in returns) / (len(returns) - 1)
    if variance <= 0.0:
        raise ValueError("normal trial Sharpe requires positive variance")
    return mean / sqrt(variance) * sqrt(252.0)


def _probability(value: object, name: str) -> float:
    if isinstance(value, bool):
        raise ValueError(f"{name} must be a probability")
    try:
        number = float(value)
    except (TypeError, ValueError) as error:
        raise ValueError(f"{name} must be a probability") from error
    if not isfinite(number) or not 0.0 <= number <= 1.0:
        raise ValueError(f"{name} must be between zero and one")
    return number


def _date(value: object, name: str) -> date:
    if isinstance(value, datetime):
        raise ValueError(f"{name} must be a date")
    if isinstance(value, date):
        return value
    if not isinstance(value, str):
        raise ValueError(f"{name} must be an ISO date")
    try:
        return date.fromisoformat(value)
    except ValueError as error:
        raise ValueError(f"{name} must be an ISO date") from error


def _aware_datetime(value: object, name: str) -> datetime:
    if not isinstance(value, str):
        raise ValueError(f"{name} must be an ISO timestamp")
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as error:
        raise ValueError(f"{name} must be an ISO timestamp") from error
    if parsed.tzinfo is None or parsed.utcoffset() is None:
        raise ValueError(f"{name} must be timezone-aware")
    return parsed


def _issuer(value: object, name: str) -> str:
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{name} issuer is required")
    return value.strip()


def _digest(value: object, name: str) -> str:
    if (
        not isinstance(value, str)
        or len(value) != 64
        or any(character not in "0123456789abcdef" for character in value)
    ):
        raise ValueError(f"{name} must be a lowercase SHA-256 digest")
    return value


